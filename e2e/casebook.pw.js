import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import cases from '../content/deduction-cases.json' with { type: 'json' };

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'deduction-browser-'));
const port = 3117, base = `http://127.0.0.1:${port}`;
const child = spawn(process.execPath, ['server/index.js'], { env: { ...process.env, NODE_ENV: 'production', PORT: String(port), FIELDNOTES_DATA_DIR: dir }, stdio: 'pipe' });
let browser;
try {
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Server timeout')), 10000); child.stdout.on('data', d => { if (String(d).includes('Game running')) { clearTimeout(timer); resolve(); } }); child.on('exit', code => reject(new Error(`Server exit ${code}`))); });
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'], env: { ...process.env, XDG_CONFIG_HOME: '/tmp/deduction-browser-config', XDG_CACHE_HOME: '/tmp/deduction-browser-cache' } });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await context.addInitScript(() => {
    window.sharedResults = [];
    Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
    Object.defineProperty(navigator, 'share', { configurable: true, value: async data => window.sharedResults.push({ text: data.text, files: data.files.map(f => ({ size: f.size, type: f.type })) }) });
  });
  const page = await context.newPage(), errors = [], requested = [];
  async function viewShot(target, file) { await target.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' })); await target.waitForTimeout(400); await target.screenshot({ path: file }); }
  page.on('pageerror', e => errors.push(e.message)); page.on('request', r => requested.push(r.url()));
  await page.goto(base + '/?mode=casebook');
  await page.locator('#show-choices').waitFor();
  await page.locator('.case-scene img').evaluate(img => img.decode());
  assert.equal(await page.locator('h1').textContent(), cases[0].title);
  assert.equal(await page.locator('.record-pin').count(), 0);
  assert.equal(await page.locator('.report-blank').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(requested.some(url => /legacy-main|maplibre|arcgisonline|openfreemap/.test(url)), false, 'new game does not load the old map engine or external map data');
  for (const c of cases) assert.ok(!(await page.locator('body').textContent()).includes(c.location.prefecture));
  await viewShot(page, '/tmp/ibun-demo-question-mobile.png');
  await page.locator('#book-map').click();
  assert.equal(await page.locator('.record-card').count(), 0);
  assert.ok((await page.locator('.collection-heading').textContent()).includes('増えていきます'));
  await page.locator('#resume-case').click();
  await page.locator('[data-clue="a"]').click();
  await page.locator('#evidence-modal[open]').waitFor();
  assert.equal(await page.locator('.evidence-paper > p').last().textContent(), cases[0].clues[0].body);
  await page.waitForFunction(() => document.querySelector('.paper-sheet').getAnimations().some(a => a.playState === 'running'));
  await page.screenshot({ path: '/tmp/ibun-demo-evidence-opening.png' });
  await page.keyboard.press('Escape');
  await page.reload(); await page.locator('#show-choices').waitFor();
  assert.equal(await page.locator('[data-clue="a"]').getAttribute('class').then(x => x.includes('opened')), true);
  assert.equal(await page.locator('#evidence-modal').evaluate(el => el.open), false, 'reload does not replay an old opening');
  await page.locator('[data-clue="b"]').click(); await page.locator('#continue-thinking').click();
  await page.locator('#show-choices').click();
  await page.locator('#submit-case').waitFor();
  assert.equal(await page.locator('#submit-case').isDisabled(), true);
  assert.equal(await page.locator('.report-blank').count(), 2);
  await page.locator('[data-for-slot="who"][data-word="a"]').click();
  assert.equal(await page.locator('#submit-case').isDisabled(), true);
  await page.locator('[data-slot="who"]').click();
  await page.locator('[data-for-slot="who"][data-word="b"]').click();
  await page.locator('[data-for-slot="why"][data-word="c"]').click();
  assert.equal(await page.locator('#submit-case').isEnabled(), true);
  assert.equal(await page.locator('.report-blank.filled').count(), 2);
  await viewShot(page, '/tmp/ibun-demo-report-mobile.png');
  await page.locator('#review-situation').click(); await page.locator('#show-choices').click();
  assert.equal(await page.locator('.report-blank.filled').count(), 2, 'draft stays while reviewing the situation');
  // A response can be lost after the server commits. The UI reconciles it.
  await page.route('**/api/casebook/answer', async route => { await route.fetch(); await route.abort('failed'); });
  await page.locator('#submit-case').click(); await page.locator('#reveal-region').waitFor();
  await page.unroute('**/api/casebook/answer');
  assert.ok((await page.locator('.answer-verdict').textContent()).includes('+100'));
  assert.equal(await page.locator('.proof-card').count(), 2);
  assert.equal(await page.locator('.book-error').count(), 0, 'committed response loss is not shown as an unsaved answer');
  assert.ok(!(await page.locator('body').textContent()).includes('宮崎県'));
  assert.equal(await page.locator('.source-details').count(), 0);
  await viewShot(page, '/tmp/ibun-demo-answer-mobile.png');
  await page.locator('#reveal-region').click(); await page.locator('.location-heading').waitFor();
  assert.ok((await page.locator('h1').textContent()).includes('宮崎県'));
  assert.equal(await page.locator('.record-pin').count(), 1);
  assert.equal(requested.some(url => url.includes('/api/casebook/photo/')), false, 'aerials are not fetched until explicitly requested');
  await page.locator('.aerial-details summary').click();
  await page.locator('.aerial-details img[src]').waitFor({ state: 'attached' });
  await page.locator('.aerial-details img').evaluate(img => img.decode());
  await page.locator('.aerial-details summary').click();
  await page.locator('.source-details summary').click();
  assert.equal(await page.locator('.source-details article a').getAttribute('href'), cases[0].sources[0].url);
  await page.locator('.source-details summary').click();
  await viewShot(page, '/tmp/ibun-demo-place-mobile.png');
  await page.locator('#book-map').click();
  assert.equal(await page.locator('.record-card').count(), 1);
  await page.locator('.record-card').click(); await page.locator('#next-case').click();
  await page.locator('#show-choices').waitFor();
  assert.equal(await page.locator('h1').textContent(), cases[1].title);
  await page.locator('#show-choices').click();
  await page.locator('[data-for-slot="who"][data-word="b"]').click();
  await page.locator('[data-for-slot="why"][data-word="c"]').click();
  await page.locator('#submit-case').click(); await page.locator('#reveal-region').waitFor();
  assert.ok((await page.locator('.answer-verdict').textContent()).includes('+50'));
  await page.reload(); await page.locator('#reveal-region').waitFor();
  assert.equal(await page.locator('.submitted-words .matched').count(), 1);
  assert.ok(!(await page.locator('body').textContent()).includes('和歌山県'));
  await page.locator('#reveal-region').click(); await page.locator('#next-case').click();
  await page.locator('#show-choices').click(); await page.locator('#skip-case').click();
  await page.locator('#reveal-region').waitFor();
  assert.ok((await page.locator('.answer-verdict').textContent()).includes('+0'));
  await page.locator('#reveal-region').click(); await page.locator('#next-case').click();
  await page.locator('#share-casebook:enabled').waitFor();
  assert.equal(await page.locator('.summary-score').textContent(), '150 / 300 点');
  assert.equal(await page.locator('.summary-records button').count(), 3);
  assert.equal(await page.locator('.book-ad').count(), 1);
  await page.locator('#share-casebook').click();
  const shares = await page.evaluate(() => window.sharedResults);
  assert.equal(shares.length, 1); assert.ok(shares[0].files[0].size > 5000); assert.equal(shares[0].files[0].type, 'image/png');
  for (const c of cases) { assert.ok(!shares[0].text.includes(c.location.prefecture)); assert.ok(!shares[0].text.includes(c.location.place)); }
  const download = page.waitForEvent('download'); await page.locator('#save-casebook').click();
  assert.match((await download).suggestedFilename(), /ibun-demo-.*\.png/);
  await page.reload(); await page.locator('.summary-score').waitFor();
  assert.equal(await page.locator('.summary-score').textContent(), '150 / 300 点');
  await page.locator('#summary-map').click();
  assert.equal(await page.locator('.record-pin').count(), 3);
  assert.equal(await page.locator('.record-card').count(), 3);
  await viewShot(page, '/tmp/ibun-demo-collection-mobile.png');
  assert.deepEqual(errors, []);

  const narrow = await browser.newContext({ viewport: { width: 320, height: 740 }, reducedMotion: 'reduce', isMobile: true, hasTouch: true });
  const small = await narrow.newPage(); await small.goto(base + '/'); await small.locator('#show-choices').waitFor();
  await small.locator('[data-clue="a"]').click();
  assert.equal(await small.locator('.paper-sheet').evaluate(el => getComputedStyle(el).animationName), 'none');
  await small.locator('#continue-thinking').click(); await small.locator('#show-choices').click();
  await small.locator('[data-for-slot="who"][data-word="a"]').click(); await small.locator('[data-for-slot="why"][data-word="a"]').click();
  assert.equal(await small.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await viewShot(small, '/tmp/ibun-demo-report-320.png');
  await small.locator('#submit-case').click(); await small.locator('#reveal-region').waitFor();
  assert.ok((await small.locator('.answer-verdict').textContent()).includes('+0'));
  assert.ok((await small.locator('.answer-verdict').textContent()).includes('別の答え'));
  await small.locator('#reveal-region').click();
  await small.locator('.location-heading').waitFor();
  assert.equal(await small.locator('.record-pin').count(), 1, 'fully incorrect reports also receive a map record');
  await small.route('**/api/casebook/photo/**', route => route.abort('failed'));
  await small.locator('.aerial-details summary').click(); await small.locator('.photo-failure:not([hidden])').waitFor();
  assert.equal(await small.locator('.source-details summary').isVisible(), true);
  await narrow.close();

  const desktop = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const wide = await desktop.newPage(); await wide.goto(base); await wide.locator('#show-choices').waitFor();
  await wide.locator('#show-choices').click(); await wide.locator('[data-for-slot="who"][data-word="b"]').click();
  await wide.locator('[data-for-slot="why"][data-word="c"]').click();
  assert.equal(await wide.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await viewShot(wide, '/tmp/ibun-demo-report-desktop.png');
  await desktop.close();
  console.log('Casebook browser passed: local-only assets, evidence opening, two-slot reports, partial credit, lost-response recovery, delayed location reveal, all-result map records, reload, mobile/320px/desktop, reduced motion, image fallback and spoiler-free share. Native share is mocked.');
} finally { await browser?.close(); child.kill(); fs.rmSync(dir, { recursive: true, force: true }); }
